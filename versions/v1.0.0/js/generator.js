/* PowerShell script generator (idempotent, Windows 10/11 safe) */
(function(){
  function escapePsString(s){
    if (s == null) return "";
    return String(s).replace(/`/g, "``").replace(/"/g, "`\"");
  }
  function listToPowershellArray(items){
    const q = items.map(s => `'` + String(s).replace(/'/g, "''") + `'`).join(',');
    return `@(${q})`;
  }
  function buildScript({ root, folders, files, includeTreeCmd = true, dryRunHeader = false }){
    const safeRoot = escapePsString(root);
    const folderArr = listToPowershellArray(folders);
    const fileArr   = listToPowershellArray(files);
    const header = `# === Project Stack Creator (idempotent) ===
# Generated by Project Scaffold Dashboard - A Phil Forster Production
# Target: "${safeRoot}"
${dryRunHeader ? "# DRY-RUN HEADER (visual only): Review, then execute in PowerShell" : ""}`;
    const body = `
# 0) Validate root
$root = "${safeRoot}"
if (-not (Test-Path -Path $root -PathType Container)) {
  Write-Error "Path '$root' does not exist (or is not a folder). Aborting."
  exit 1
}
Set-Location -Path $root

# 1) Required folders and files
$dirs = ${folderArr}
$files = ${fileArr}

# 2) Create folders if missing
foreach ($d in $dirs) {
  if (-not (Test-Path -Path $d -PathType Container)) {
    New-Item -ItemType Directory -Path $d | Out-Null
    Write-Host "[+] Created folder: $d"
  } else {
    Write-Host "[=] Folder exists: $d"
  }
}

# 3) Ensure parent folders for nested files exist
foreach ($f in $files) {
  $parent = Split-Path -Path $f -Parent
  if ($parent -and -not (Test-Path -Path $parent -PathType Container)) {
    New-Item -ItemType Directory -Path $parent | Out-Null
    Write-Host "[+] Created folder (parent): $parent"
  }
}

# 4) Create files (idempotent)
foreach ($f in $files) {
  if (-not (Test-Path -Path $f -PathType Leaf)) {
    New-Item -ItemType File -Force -Path $f | Out-Null
    Write-Host "[+] Created file: $f"
  } else {
    Write-Host "[=] File exists: $f"
  }
}

# 5) Verify
Write-Host ""
Write-Host "Scaffold created/verified at: $root" -ForegroundColor Green
${includeTreeCmd ? "cmd /c 'tree . /f'" : 'Write-Host "(tree output suppressed)"'}
`.trim();
    return `${header}\n\n${body}\n`;
  }
  window.Generator = { buildScript };
})();
